SELECT COUNT(*)
FROM (
    SELECT ROW_NUMBER() OVER (
        PARTITION BY INVOICENO, STOCKCODE, DESCRIPTION,
        QUANTITY, INVOICEDATE, UNITPRICE, CUSTOMERID, COUNTRY
        ORDER BY INVOICENO
    ) AS RN
    FROM ONLINE_RETAIL
)
WHERE RN > 1;

SELECT COUNT(*)
FROM ONLINE_RETAIL
WHERE QUANTITY < 0;

SELECT COUNT(*)
FROM ONLINE_RETAIL
WHERE UNITPRICE <= 0;

SELECT COUNT(DISTINCT COUNTRY)
FROM ONLINE_RETAIL; 

SELECT SUM(QUANTITY * UNITPRICE) AS TOTAL_REVENUE
FROM ONLINE_RETAIL
WHERE QUANTITY > 0
AND UNITPRICE > 0;

SELECT SUM(QUANTITY) AS TOTAL_UNITS_SOLD
FROM ONLINE_RETAIL
WHERE QUANTITY > 0;

SELECT COUNT(DISTINCT INVOICENO) AS TOTAL_ORDERS
FROM ONLINE_RETAIL
WHERE QUANTITY > 0;

SELECT COUNT(DISTINCT CUSTOMERID) AS TOTAL_CUSTOMERS
FROM ONLINE_RETAIL;

SELECT
    CUSTOMERID,
    SUM(QUANTITY * UNITPRICE) AS TOTAL_SPENT
FROM ONLINE_RETAIL
WHERE CUSTOMERID IS NOT NULL
AND QUANTITY > 0
AND UNITPRICE > 0
GROUP BY CUSTOMERID
ORDER BY TOTAL_SPENT DESC
FETCH FIRST 10 ROWS ONLY;

SELECT
    STOCKCODE,
    MAX(DESCRIPTION) AS PRODUCT_NAME,
    SUM(QUANTITY) AS TOTAL_SOLD
FROM ONLINE_RETAIL
WHERE QUANTITY > 0
GROUP BY STOCKCODE
ORDER BY TOTAL_SOLD DESC
FETCH FIRST 10 ROWS ONLY;

SELECT
    COUNTRY,
    SUM(QUANTITY * UNITPRICE) AS TOTAL_SALES
FROM ONLINE_RETAIL
WHERE QUANTITY > 0
AND UNITPRICE > 0
GROUP BY COUNTRY
ORDER BY TOTAL_SALES DESC;

SELECT
    TO_CHAR(INVOICEDATE, 'YYYY-MM') AS SALES_MONTH,
    SUM(QUANTITY * UNITPRICE) AS TOTAL_SALES
FROM ONLINE_RETAIL
WHERE QUANTITY > 0
AND UNITPRICE > 0
GROUP BY TO_CHAR(INVOICEDATE, 'YYYY-MM')
ORDER BY SALES_MONTH;

